"""Exception hierarchy. Messages are user-facing (Indonesian) and never contain secrets."""


class SentinelError(Exception):
    """Base class for expected, user-presentable errors."""


class StartupError(SentinelError): ...
class KeyringUnavailableError(StartupError): ...
class KeyMissingError(StartupError): ...
class DatabaseKeyError(StartupError): ...
class SqlCipherUnavailableError(StartupError): ...
class ValidationError(SentinelError): ...
class NotFoundError(SentinelError): ...
class PermissionDeniedError(SentinelError): ...
class AuthenticationError(SentinelError): ...
class AccountLockedError(AuthenticationError): ...
class UsbValidationError(AuthenticationError): ...
class BiometricError(AuthenticationError): ...
class DeviceError(SentinelError): ...
class IntegrityError(SentinelError): ...
class DecryptionError(IntegrityError): ...
